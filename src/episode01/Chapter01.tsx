type Point = {x: number; y: number};
const clamp = (v: number) => Math.max(0, Math.min(1, v));
const smooth = (start: number, end: number, t: number) => {
  const s = clamp((t - start) / (end - start));
  return s * s * (3 - 2 * s);
};
const lerp = (a: number, b: number, s: number) => a + (b - a) * s;

export type View = {xFocus: number; zoom: number; perspective: number};

export function viewAt(t: number): View {
  const approach = smooth(12, 24, t);
  return {
    xFocus: lerp(0, -1.65, approach),
    zoom: lerp(1.0, 1.43, approach),
    perspective: approach,
  };
}

/** A didactic pseudo-perspective dolly, not the UE camera matrix. */
export function project([x, y, z]: Vec3, view: View): Point {
  const depth = 1 + view.perspective * (0.07 * (x + 5.5) - 0.10 * z);
  const scale = (102 * view.zoom) / Math.max(0.55, depth);
  return {
    x: 960 + (x - view.xFocus) * scale,
    y: 511 - y * 130 * view.zoom / Math.max(0.55, depth) -
      z * 88 * view.zoom / Math.max(0.55, depth),
  };
}

function averageColor(tri: WallTriangle): string {
  const [a, b, c] = tri.corners;
  const ab = [b[0]-a[0], b[1]-a[1], b[2]-a[2]];
  const ac = [c[0]-a[0], c[1]-a[1], c[2]-a[2]];
  const nx = ab[1]*ac[2] - ab[2]*ac[1];
  const ny = ab[2]*ac[0] - ab[0]*ac[2];
  const nz = ab[0]*ac[1] - ab[1]*ac[0];
  const mag = Math.hypot(nx, ny, nz) || 1;
  const lighting = clamp((0.3*nx + 0.4*ny + 0.9*nz) / mag * 0.6 + 0.4);
  return 'hsl(207, 24%, ' + (14 + lighting * 25).toFixed(1) + '%)';
}

const averageShades = new WeakMap<WallTriangle, string>();
function shade(tri: WallTriangle) {
  let result = averageShades.get(tri);
  if (!result) {
    result = averageColor(tri);
    averageShades.set(tri, result);
  }
  return result;
}

export function TriangleSurface({mode, view, colorProgress, wireOpacity, glow}: {
  mode: WallMode;
  view: View;
  colorProgress: number;
  wireOpacity: number;
  glow: number;
}) {
  const triangles = wallMeshes[mode].triangles;
  return (
    <g>
      {triangles.map((tri, i) => {
        const polygon = tri.corners.map((p) => {
          const pt = project(p, view);
          return pt.x.toFixed(2) + ',' + pt.y.toFixed(2);
        }).join(' ');
        return (
          <g key={mode + '-' + i}>
            <polygon
              points={polygon}
              fill={shade(tri)}
              stroke={INK}
              strokeWidth={mode === 'coarse' ? 1.4 : 1.0}
              strokeOpacity={wireOpacity}
              strokeLinejoin="round"
            />
            {colorProgress > 0.001 && (
              <polygon
                points={polygon}
                fill={PALETTE[tri.strip % PALETTE.length]}
                fillOpacity={colorProgress * (0.37 + 0.10 * glow)}
                stroke="none"
              />
            )}
          </g>
        );
      })}
    </g>
  );
}

function stripBoundaryPolyline(strip: number, view: View): string {
  const x = WORLD_LEFT + strip / STRIPS * (WORLD_RIGHT-WORLD_LEFT);
  // Choose vertices already generated by the fine mesh, so that displayed
  // boundary polylines coincide with actual triangles rather than straight
  // screen-space approximation.
  const verts = new Map<string, Vec3>();
  for (const tri of wallMeshes.fine.triangles) {
    for (const p of tri.corners) {
      if (Math.abs(p[0] - x) < 1e-7) verts.set(p[1].toFixed(7), p);
    }
  }
  const ordered = [...verts.values()].sort((a, b) => a[1]-b[1]);
  return ordered.map((p, i) => {
    const q = project(p, view);
    return (i === 0 ? 'M' : 'L') + q.x.toFixed(1) + ' ' + q.y.toFixed(1);
  }).join(' ');
}

export function ClusterEdges({view, opacity}: {view: View; opacity: number}) {
  return (
    <g opacity={opacity}>
      {Array.from({length: STRIPS - 1}, (_, i) => i + 1).map((i) => (
        <path
          key={i}
          d={stripBoundaryPolyline(i, view)}
          fill="none"
          stroke={GOLD}
          strokeWidth={3.2}
          strokeOpacity={0.75}
        />
      ))}
    </g>
  );
}


